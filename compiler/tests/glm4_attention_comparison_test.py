"""Compare baseline attention against completed Flash execution on identical inputs.

The reused projection outputs and KV fixture come from glm4_decode_test.py.
Only the attention invocation is benchmarked here; no host result is fed back
into an executed model graph. Both binaries must be generated by this build;
an older executed Flash binary may be reused only after a byte-identical
recompilation when explicitly requested.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import sys

import numpy as np
from glm4_decode_test import attention, decoder_config, errors, read
from activation_batch_matmul_test import compile_graph, run
from glm4_flash_packed_u_test import graph_digest
from summarize_glm4_flash import phase_timing


def copy_replay_kernel(source, replay):
    """Redirect generated artifacts without changing original input references."""
    original = source.read_text()
    replacement = json.dumps(str(replay.resolve()))
    text, count = re.subn(r'(ftlpu\.artifact_directory\s*=\s*)"(?:\\.|[^"\\])*"',
                         lambda match: match[1]+replacement, original)
    assert count == 1, 'expected one Flash artifact directory'
    kernel = replay/'kernel.mlir'
    kernel.write_text(text)
    return kernel


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    for name in ('checkpoint', 'flash-results', 'build-dir', 'target-config', 'output-dir'):
        parser.add_argument('--' + name, type=Path, required=True)
    parser.add_argument('--batches', type=int, nargs='+', default=[1, 32])
    parser.add_argument('--executed-flash-results', type=Path,
                        help='Completed optimized Flash root; fixtures/projections still come from --flash-results')
    parser.add_argument('--verify-flash-recompile', action='store_true',
                        help='If the compiler changed, require byte-identical recompilation of the executed Flash program')
    args = parser.parse_args()
    build = args.build_dir.resolve()
    extension = '.exe' if sys.platform == 'win32' else ''
    digest = lambda path: hashlib.sha256(path.read_bytes()).hexdigest()
    compiler_hash = digest(build/'compiler'/('ftlpu-compile' + extension))
    signature = json.loads((args.flash_results/'signature.json').read_text())
    assert signature['target'] == digest(args.target_config), 'different hardware target'
    runner_hash = digest(build/'runtime'/('compiled_stage_file_runner' + extension))
    assert signature['runner'] == runner_hash, 'different runtime runner'
    clock = json.loads(args.target_config.read_text())['external_memory']['lpu_clock_mhz']
    config = decoder_config(json.loads((args.checkpoint/'config.json').read_text()))
    config['head_dim'] = 128
    for batch in args.batches:
        source = args.flash_results.resolve()/f'batch{batch}'
        executed_root = (args.executed_flash_results or args.flash_results).resolve()
        executed = executed_root/f'batch{batch}/attention'
        stamp = json.loads((executed/'completed.json').read_text())
        changed_compiler = stamp['compiler_sha256'] != compiler_hash
        assert not changed_compiler or args.verify_flash_recompile, 'Flash binary came from a different compiler'
        assert stamp['binary_sha256'] == digest(executed/'program.ftlpu')
        source_record = json.loads((source/'result.json').read_text())
        assert source_record['status'] == 'passed' and source_record['attention_strategy'] == 'flash'
        assert source_record['checkpoint_provenance']['config_sha256'] == digest(args.checkpoint/'config.json')
        projection_paths = [source/f'projections/actual.{i}.bin' for i in range(3)]
        q, k, v = [read(path, (batch, width)) for path, width in zip(projection_paths, (4096, 256, 256))]
        with np.load(source/'reference.npz', allow_pickle=False) as fixture:
            past_key, past_value = fixture['past_key'], fixture['past_value']
            fixture_fingerprint = str(fixture['fingerprint'])
        if args.executed_flash_results is not None:
            accepted = json.loads((executed.parent/'result.json').read_text())
            assert accepted['status'] == 'passed', 'optimized Flash execution was not accepted'
            assert accepted['batch'] == batch and accepted['past_len'] == 32 and accepted['layer'] == 0
            assert accepted['icu_encoding'] == 'raw-macro'
            assert accepted['target_sha256'] == signature['target'] and accepted['runner_sha256'] == runner_hash
            assert accepted['compiler_sha256'] == stamp['compiler_sha256']
            assert accepted['binary_sha256'] == stamp['binary_sha256']
            assert accepted['fixture_fingerprint'] == fixture_fingerprint
            assert accepted['projection_output_sha256'] == [digest(path) for path in projection_paths]
            assert accepted['graph_sha256'] == graph_digest(executed) == graph_digest(source/'attention')
            assert accepted['actual_runtime_program_sha256']['streamed_flash'] == digest(executed/'actual.runtime.ftlpu')
            assert accepted['timing']['streamed_flash'] == phase_timing(executed, clock)
        graph, outputs = attention(q, k, v, past_key, past_value, config, strategy='baseline')
        folder = args.output_dir.resolve()/f'batch{batch}'/'attention'
        assert all(folder != original and not original.is_relative_to(folder)
                   for original in (source/'attention', executed)), 'output would replace a comparison source'
        print(f'batch={batch}: baseline attention compile', flush=True)
        exe, env, binary = compile_graph(graph, outputs, folder, build,
                                         args.target_config.resolve(), fp32_spills=True)
        assert compiler_hash == digest(build/'compiler'/('ftlpu-compile' + extension)), 'compiler changed during comparison'
        if changed_compiler:
            replay = folder.parent/'flash_recompile'
            replay.mkdir(exist_ok=True)
            replay_kernel = copy_replay_kernel(executed/'kernel.mlir', replay)
            print(f'batch={batch}: verify Flash binary equivalence under comparison compiler', flush=True)
            run([exe('compiler', 'ftlpu-compile'), '--input', replay_kernel,
                 '--input-stage', 'kernel', '--output', replay/'program.ftlpu',
                 '--target-config', args.target_config.resolve(), '--icu-compression', 'raw-macro',
                 '--mxm-execution', 'ws'], replay/'compile.log', env)
            assert digest(replay/'program.ftlpu') == stamp['binary_sha256'], 'recompiled Flash binary changed; execute it before comparing'
        assert compiler_hash == digest(build/'compiler'/('ftlpu-compile' + extension)), 'compiler changed during comparison'
        print(f'batch={batch}: baseline attention CModel', flush=True)
        run([exe('runtime', 'compiled_stage_file_runner'), binary, folder/'inputs.txt',
             folder/'actual', folder/'runtime.pipeline.csv'], folder/'execution.log', env)
        run([exe('runtime', 'ftlpu_icu_program_export'), folder/'actual.runtime.ftlpu',
             folder/'icu_programs', '--pre-execution-dir', folder/'actual.pre_execution'],
            folder/'export.log', env)
        (folder/'completed.json').write_text(json.dumps(dict(binary_sha256=digest(binary),
            compiler_sha256=compiler_hash, semantic_graph_sha256=graph_digest(folder))))
        actual = read(folder/'actual.0.bin', (batch, 4096))
        key, value = [read(folder/f'actual.{i}.bin', (batch, 33, 2, 128)) for i in (1, 2)]
        assert np.array_equal(key[:, :32], past_key)
        assert np.array_equal(value[:, :32], past_value)
        score = np.einsum('bhqd,bthd->bhqt', q.reshape(batch, 2, 16, 128), key)/np.sqrt(128)
        probability = np.exp(score-score.max(-1, keepdims=True))
        probability /= probability.sum(-1, keepdims=True)
        expected = np.einsum('bhqt,bthd->bhqd', probability, value).reshape(batch, 4096)
        metrics = errors(actual, expected)
        flash = read(executed/'actual.0.bin', (batch, 4096))
        flash_metrics = errors(flash, expected)
        assert np.isfinite(actual).all() and metrics['relative_l2'] < .03, metrics
        assert np.isfinite(flash).all() and flash_metrics['relative_l2'] < .03, flash_metrics
        assert np.array_equal(key, read(executed/'actual.1.bin', key.shape))
        assert np.array_equal(value, read(executed/'actual.2.bin', value.shape))
        record = dict(status='passed', scope='attention invocation only', batch=batch,
                      past_len=32, baseline=metrics, flash=flash_metrics,
                      baseline_vs_flash=errors(flash, actual), historical_kv_bit_exact=True,
                      compiler_sha256=compiler_hash, binary_sha256=digest(binary),
                      flash_executed_compiler_sha256=stamp['compiler_sha256'],
                      comparison_build_verification=('byte_identical_flash_recompile' if changed_compiler else 'same_compiler'),
                      flash_binary_sha256=stamp['binary_sha256'],
                      target_sha256=digest(args.target_config), runner_sha256=runner_hash,
                      fixture_fingerprint=fixture_fingerprint,
                      projection_output_sha256=[digest(path) for path in projection_paths],
                      flash_results=str(executed_root), icu_encoding='raw-macro', clock_mhz=clock,
                      timing=dict(baseline=phase_timing(folder, clock), flash=phase_timing(executed, clock)))
        before, after = (record['timing'][kind]['runtime_cycles'] for kind in ('baseline', 'flash'))
        record.update(flash_cycles_saved_vs_baseline=before-after,
                      flash_speedup_vs_baseline=before/after,
                      flash_latency_reduction_percent_vs_baseline=100*(before-after)/before)
        (folder.parent/'result.json').write_text(json.dumps(record, indent=2))
        print(record, flush=True)


if __name__ == '__main__':
    main()
