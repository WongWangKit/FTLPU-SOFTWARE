#!/usr/bin/env python3
"""Checks vector SRAM tiling, row reductions and FP32 state across ICU stages."""
import argparse
import sys
from pathlib import Path
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "tools"))
from qwen3_5_compiled_layer import CompiledStages, VectorGraph, bf16
from qwen3_5_reference import Qwen35DeltaConfig


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--compile", type=Path, required=True)
    p.add_argument("--runner", type=Path, required=True)
    p.add_argument("--output-dir", type=Path, required=True)
    a = p.parse_args()
    stages = CompiledStages(a.compile.resolve(), a.runner.resolve(), a.output_dir.resolve())
    x = (np.arange(4100, dtype=np.float32) % 32).reshape(2, 2050)
    np.testing.assert_array_equal(stages.alu("tiled_map", x, immediate=2), x * 2)
    x = (np.arange(33 * 128, dtype=np.float32) % 8 / 8).reshape(33, 128)
    np.testing.assert_array_equal(stages.alu("tiled_reduction", x, x, reduce=True),
                                  np.sum(x * x, axis=1, keepdims=True))
    # Reuse one stream for x*x. Both row and column broadcasting must be
    # generated by MEM domains, and a returned early branch must stay live
    # while the compiler reuses scratch banks for subsequent values.
    x = np.arange(24, dtype=np.float32).reshape(3, 8) / 8
    bias = np.array([[0.25], [0.5], [0.75]], np.float32)
    gamma = np.arange(8, dtype=np.float32).reshape(1, 8) / 8 + 1
    graph = VectorGraph(stages, "ssa_branch_broadcast", [(x, "f32"), (bias, "f32"), (gamma, "f32")])
    squared = graph.add(0, 0)
    shifted = graph.add(squared, 1, kind="add")
    result = graph.add(shifted, 2)
    for _ in range(30):
        result = graph.add(result, kind="add", immediate=0.25)
    # Optimizers can erase or share locations. Scheduling must still follow
    # SSA stage identity, rather than treating every unknown location as one.
    graph.lines = [line + " loc(unknown)" for line in graph.lines]
    square_actual, result_actual = graph.finish((squared, result))
    np.testing.assert_array_equal(square_actual, x * x)
    np.testing.assert_array_equal(result_actual, (x * x + bias) * gamma + 7.5)
    c = Qwen35DeltaConfig(64, 128, 1, 2, 64, 64)
    rng = np.random.default_rng(352)
    q, k, v = [bf16(rng.normal(0, 0.03, (9, 128)).astype(np.float32)) for _ in range(3)]
    decay = np.full((9, 2), 0.97, np.float32)
    beta = np.full((9, 2), 0.5, np.float32)
    initial = rng.normal(0, 0.01, (128, 64)).astype(np.float32)
    actual, final = stages.delta(q, k, v, decay, beta, initial, c)
    state = initial.reshape(2, 64, 64).copy()
    expected = np.empty((9, 2, 64), np.float32)
    for token in range(9):
        for head in range(2):
            qi, ki, vi = [x[token].reshape(2, 64)[head] for x in (q, k, v)]
            state[head] *= decay[token, head]
            remembered = np.sum(state[head] * ki[:, None], axis=0)
            delta = (vi - remembered) * beta[token, head]
            state[head] += ki[:, None] * delta[None, :]
            expected[token, head] = bf16(np.sum(state[head] * qi[:, None], axis=0))
    np.testing.assert_allclose(actual, expected.reshape(9, 128), atol=3e-6, rtol=0.005)
    np.testing.assert_allclose(final, state.reshape(128, 64), atol=3e-7, rtol=2e-5)
    # Real Qwen3.5 head geometry, multiple value blocks and a nonzero FP32
    # initial state. The optimized time/head tiling must retain dependencies.
    c = Qwen35DeltaConfig(1024, 3584, 1, 1, 128, 128)
    q, k, v = [bf16(rng.normal(0, 0.03, (5, 128)).astype(np.float32)) for _ in range(3)]
    decay = np.full((5, 1), 0.97, np.float32)
    beta = np.full((5, 1), 0.5, np.float32)
    initial = rng.normal(0, 0.01, (128, 128)).astype(np.float32)
    actual, final = stages.delta(q, k, v, decay, beta, initial, c)
    state = initial.copy()
    expected = np.empty_like(v)
    for token in range(5):
        state *= decay[token, 0]
        remembered = np.sum(state * k[token, :, None], axis=0)
        delta = (v[token] - remembered) * beta[token, 0]
        state += k[token, :, None] * delta[None, :]
        expected[token] = bf16(np.sum(state * q[token, :, None], axis=0))
    np.testing.assert_allclose(actual, expected, atol=3e-6, rtol=0.005)
    np.testing.assert_allclose(final, state, atol=3e-7, rtol=2e-5)
    print("vector SSA liveness/broadcast, tiling, reduction and recurrent state transfer passed")


if __name__ == "__main__":
    main()
